-- TAXJIKIM 로컬 개발용 테이블 생성 SQL (MySQL 8.0)
-- 출처: back/local/schema.dbml 및 기능별 DBML의 14개 테이블
-- 실제 서버의 덤프가 아닌 설계 변환본이다. INSERT 데이터는 포함하지 않는다.
-- 새 로컬 DB에 한 번 실행한다. 기존 테이블을 삭제하거나 변경하지 않는다.
-- 서버의 최신 구조와 일치하는지는 서버 복구 후 확인해야 한다.
SET NAMES utf8mb4;
CREATE DATABASE IF NOT EXISTS `TAXJIKIM` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `TAXJIKIM`;

CREATE TABLE `users` (
  `USER_ID` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `LOGIN_ID` VARCHAR(50) NOT NULL UNIQUE,
  `PASSWORD` VARCHAR(255) NOT NULL,
  `NAME` VARCHAR(50) NOT NULL,
  `NICKNAME` VARCHAR(50) NOT NULL UNIQUE,
  `EMAIL` VARCHAR(255) NOT NULL UNIQUE COMMENT '[추가] 이메일 인증·아이디/비번 찾기·메일 발송 (1,5,6,37,40,46)',
  `BIRTH_DATE` DATE NULL COMMENT '[변경] 관리자 계정은 없음. 일반 회원 가입 시 필수는 앱에서 검증',
  `PROFILE_IMAGE_URL` VARCHAR(255) NULL,
  `USER_ROLE` VARCHAR(20) NOT NULL DEFAULT 'USER' COMMENT 'USER / ADMIN',
  `USER_STATUS` VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE / LOCKED / DORMANT / BANNED',
  `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `LAST_LOGIN_AT` DATETIME NULL COMMENT '마지막 로그인 시각'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `USER_LOGIN_SECURITY` (
  `USER_ID` BIGINT NOT NULL PRIMARY KEY COMMENT 'users.USER_ID와 같은 값 (1:1)',
  `LOGIN_FAIL_COUNT` INT NOT NULL DEFAULT 0 COMMENT '5회 초과 시 잠금',
  `LOCK_LEVEL` TINYINT NOT NULL DEFAULT 0 COMMENT '0:없음 1:30초 2:1분 3:3분 4:5분 (4단계 뒤 또 실패하면 자동 정지)',
  `LOCKED_UNTIL` DATETIME NULL COMMENT '잠금 해제 시각',
  `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `USER_SANCTIONS` (
  `SANCTION_ID` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `USER_ID` BIGINT NOT NULL COMMENT '제재 대상 회원',
  `ACTION_TYPE` VARCHAR(10) NOT NULL COMMENT 'SUSPEND / RELEASE',
  `SOURCE` VARCHAR(20) NOT NULL COMMENT 'LOGIN_FAIL / REPORT / ADMIN',
  `REASON` VARCHAR(255) NULL COMMENT '예: 신고 누적 3건',
  `ADMIN_ID` BIGINT NULL COMMENT '처리 관리자 (자동 제재는 NULL)',
  `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY (`USER_ID`, `CREATED_AT`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `POSTS` (
  `POST_ID` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `USER_ID` BIGINT NOT NULL COMMENT '작성자. NOTICE·FAQ는 USER_ROLE=ADMIN만 작성 (앱 검증)',
  `BOARD_TYPE` VARCHAR(30) NOT NULL COMMENT '[변경] INFO(정보 공유) / TIP(팁) / NOTICE(공지) / FAQ / QNA. 기존 CATEGORY 컬럼은 삭제 (8,12,19,21,53)',
  `JOB_CATEGORY` VARCHAR(50) NULL COMMENT '[추가] 직군 태그 (8,11,13)',
  `TITLE` VARCHAR(255) NOT NULL COMMENT 'FAQ는 질문',
  `CONTENT` TEXT NOT NULL COMMENT 'FAQ는 답변',
  `IS_PUBLIC` BOOLEAN NOT NULL DEFAULT true COMMENT '[추가] QNA만 의미. 비공개면 본인·관리자만 조회 (21,22,45)',
  `ANSWER_STATUS` VARCHAR(20) NULL COMMENT '[추가] QNA만 사용: WAITING / DONE. 관리자 답변(댓글)이 달리면 DONE (21,45,46)',
  `VIEW_COUNT` INT NOT NULL DEFAULT 0,
  `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `DELETED_AT` DATETIME NULL,
  `DELETED_BY_TYPE` VARCHAR(10) NULL COMMENT '[추가] SELF / ADMIN. ADMIN이면 "관리자에 의해 삭제된 게시글입니다" 표시 (8,43)',
  KEY (`BOARD_TYPE`, `CREATED_AT`),
  KEY (`BOARD_TYPE`, `ANSWER_STATUS`, `CREATED_AT`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `COMMENTS` (
  `COMMENT_ID` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `POST_ID` BIGINT NOT NULL,
  `USER_ID` BIGINT NOT NULL,
  `PARENT_COMMENT_ID` BIGINT NULL COMMENT '[추가] 대댓글이면 부모 댓글 ID, 일반 댓글이면 NULL. 부모는 항상 일반 댓글 (1단계) (N1,N2)',
  `CONTENT` TEXT NOT NULL,
  `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `DELETED_AT` DATETIME NULL,
  `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `DELETED_BY_TYPE` VARCHAR(10) NULL COMMENT '[추가] SELF / ADMIN (15,43)',
  KEY (`POST_ID`, `CREATED_AT`),
  KEY (`PARENT_COMMENT_ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `REPORTS` (
  `REPORT_ID` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `TARGET_TYPE` VARCHAR(20) NOT NULL COMMENT 'POST / COMMENT',
  `TARGET_ID` BIGINT NOT NULL,
  `TARGET_USER_ID` BIGINT NOT NULL COMMENT '[추가] 피신고 회원 (대상 글·댓글 작성자) (N4)',
  `REASON` VARCHAR(20) NULL COMMENT '[변경] 사유 분류(선택)',
  `REASON_DETAIL` TEXT NOT NULL COMMENT '[추가] 신고자가 입력한 사유 (18)',
  `STATUS` VARCHAR(20) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING / DONE',
  `RESULT` VARCHAR(10) NULL COMMENT '[추가] DELETE / REJECT (43,44)',
  `PROCESSED_BY` BIGINT NULL COMMENT '[추가] 처리한 관리자 (43,44)',
  `PROCESSED_AT` DATETIME NULL COMMENT '[추가]',
  `REPORTER_ID` BIGINT NOT NULL,
  `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `DELETED_AT` DATETIME NULL,
  `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY (`REPORTER_ID`, `TARGET_TYPE`, `TARGET_ID`),
  KEY (`STATUS`, `CREATED_AT`),
  KEY (`TARGET_TYPE`, `TARGET_ID`),
  KEY (`TARGET_USER_ID`, `RESULT`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `FILE_META` (
  `FILE_ID` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `POST_ID` BIGINT NULL,
  `USER_ID` BIGINT NOT NULL COMMENT '업로더. 자료실은 관리자 계정',
  `STORED_FILE_NAME` VARCHAR(255) NOT NULL,
  `FILE_PATH` VARCHAR(500) NOT NULL,
  `FILE_EXTENSION` VARCHAR(10) NOT NULL,
  `FILE_SIZE` BIGINT NOT NULL,
  `FILE_TYPE` VARCHAR(30) NOT NULL COMMENT '[변경] POST / RESOURCE(자료실) (20,22)',
  `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `DELETED_AT` DATETIME NULL,
  `ORIGINAL_FILE_NAME` VARCHAR(500) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `CHAT_ROOMS` (
  `ROOM_ID` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `USER_ID` BIGINT NOT NULL COMMENT '상담 요청 회원',
  `ADMIN_ID` BIGINT NULL COMMENT '응대 관리자 (입장 시 배정)',
  `STATUS` VARCHAR(20) NOT NULL DEFAULT 'WAITING' COMMENT 'WAITING / IN_PROGRESS / CLOSED',
  `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `CLOSED_AT` DATETIME NULL COMMENT '30일 삭제 기준 시점',
  KEY (`USER_ID`, `STATUS`),
  KEY (`STATUS`, `CREATED_AT`),
  KEY (`STATUS`, `CLOSED_AT`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `CHAT_MESSAGES` (
  `MESSAGE_ID` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `ROOM_ID` BIGINT NOT NULL,
  `SENDER_ID` BIGINT NOT NULL COMMENT '회원 또는 관리자',
  `CONTENT` TEXT NOT NULL,
  `IS_READ` BOOLEAN NOT NULL DEFAULT false COMMENT '안 읽은 메시지 배지',
  `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY (`ROOM_ID`, `CREATED_AT`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `NOTIFICATIONS` (
  `NOTIFICATION_ID` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `USER_ID` BIGINT NOT NULL COMMENT '수신자',
  `TYPE` VARCHAR(20) NOT NULL COMMENT '[추가] NOTICE / QNA_ANSWER / CHAT_REPLY / COMMENT / REPLY (12,39,40,N3)',
  `TARGET_TYPE` VARCHAR(20) NULL COMMENT '[추가] POST / COMMENT / CHAT_ROOM (클릭 시 이동, 39). 다형 참조라 FK 없음',
  `TARGET_ID` BIGINT NULL COMMENT '[추가]',
  `TITLE` VARCHAR(100) NULL,
  `MESSAGE` TEXT NULL,
  `IS_READ` BOOLEAN NOT NULL DEFAULT false,
  `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `DELETED_AT` DATETIME NULL,
  KEY (`USER_ID`, `IS_READ`, `CREATED_AT`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `TAX_INPUTS` (
  `TAX_INPUT_ID` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `USER_ID` BIGINT NOT NULL,
  `TAX_YEAR` INT NOT NULL COMMENT '[추가] 귀속 연도 (30,34,35)',
  `REGION` VARCHAR(50) NOT NULL COMMENT '회원 통계(50)에 사용. 입력 지점이 플로우에 없어 확인 필요',
  `JOB` VARCHAR(50) NOT NULL,
  `INCOME_TYPE` VARCHAR(20) NOT NULL COMMENT '[추가] FREELANCER / BUSINESS / MULTIPLE (25)',
  `AUTO_WITHHOLDING` BOOLEAN NOT NULL DEFAULT true COMMENT '[추가] 3.3% 자동 역산 (25)',
  `TOTAL_INCOME` DECIMAL(15,2) NOT NULL DEFAULT 0,
  `TOTAL_EXPENSE` DECIMAL(15,2) NOT NULL DEFAULT 0,
  `EXPECTED_TAX` DECIMAL(15,2) NOT NULL DEFAULT 0,
  `RESULT_DETAIL` JSON NULL COMMENT '[추가] 세액별 근거, 사업자 등록 전·후 비교 (29,30)',
  `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `DELETED_AT` DATETIME NULL COMMENT '[변경] NULL 허용',
  UNIQUE KEY (`USER_ID`, `TAX_YEAR`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `TAX_TRANSACTIONS` (
  `TRANSACTION_ID` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY COMMENT '[변경] 오타 TRANSAACTION_ID 수정',
  `TAX_INPUT_ID` BIGINT NOT NULL,
  `USER_ID` BIGINT NOT NULL,
  `TRANSACTION_TYPE` VARCHAR(20) NOT NULL COMMENT 'INCOME / EXPENSE',
  `TRANSACTION_DATE` DATE NOT NULL,
  `DESCRIPTION` VARCHAR(255) NOT NULL,
  `CATEGORY` VARCHAR(50) NOT NULL,
  `AMOUNT` DECIMAL(15,2) NOT NULL,
  `TAX_YEAR` INT NOT NULL,
  `IS_EDITED` BOOLEAN NOT NULL DEFAULT false COMMENT 'PDF 추출 후 보정된 내역',
  `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `DELETED_AT` DATETIME NULL,
  KEY (`USER_ID`, `TAX_YEAR`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

